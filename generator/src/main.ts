// herdsman-gen: zigbee-herdsman-converters -> zdef canonical YAML.
//
// usage: node build/src/main.js [--root <repo>] [--out definitions/generated] [--coverage coverage]
//                               [--only <model>[,<model>...]] [--stdout]
import * as fs from 'node:fs';
import * as path from 'node:path';
import {loadZhc} from './zhc';
import {translate, type Record_} from './translate';
import {toYaml} from './yaml';
import {writeCoverage} from './coverage';

function arg(name: string, dflt?: string): string | undefined {
    const i = process.argv.indexOf(`--${name}`);
    return i >= 0 ? process.argv[i + 1] : dflt;
}

export function header(version: string): string[] {
    return [
        `Generated by herdsman-gen from zigbee-herdsman-converters ${version}`,
        '(MIT, Copyright (c) 2018 Koen Kanters; see NOTICE). Do not edit: put changes in overrides/.',
    ];
}

export async function generate(root: string, only?: Set<string>) {
    const zhc = loadZhc(root);
    const out: {doc: any; rec: Record_; yaml: string}[] = [];
    const ids = new Map<string, number>();
    for (const {file, d} of zhc.definitions) {
        if (only && !only.has(d.model)) continue;
        const {doc, rec} = await translate(zhc, file, d);
        const n = ids.get(doc.id) ?? 0;
        ids.set(doc.id, n + 1);
        if (n > 0) {
            doc.id = `${doc.id}-${n + 1}`;
            rec.id = doc.id;
        }
        out.push({doc, rec, yaml: ''});
    }
    return {zhc, out};
}

// Keep the revision of an unchanged definition; bump it when the content changed.
function withRevision(file: string, doc: any, hdr: string[]): string {
    const text = (rev: number) => toYaml({...doc, revision: rev}, hdr);
    if (!fs.existsSync(file)) return text(1);
    const old = fs.readFileSync(file, 'utf8');
    const m = /^revision: (\d+)$/m.exec(old);
    const oldRev = m ? Number(m[1]) : 0;
    const body = (s: string) => s.replace(/^revision: \d+$/m, 'revision: _').replace(/^#.*\n/gm, '');
    const candidate = text(oldRev || 1);
    return body(candidate) === body(old) ? candidate : text(oldRev + 1);
}

async function main() {
    const root = path.resolve(arg('root', process.cwd())!);
    const outDir = path.resolve(root, arg('out', 'definitions/generated')!);
    const covDir = path.resolve(root, arg('coverage', 'coverage')!);
    const onlyArg = arg('only');
    const only = onlyArg ? new Set(onlyArg.split(',')) : undefined;
    const t0 = Date.now();
    const {zhc, out} = await generate(root, only);
    const hdr = header(zhc.version);
    if (process.argv.includes('--stdout')) {
        for (const o of out) process.stdout.write(`---\n${toYaml(o.doc, hdr)}`);
        return;
    }
    const written = new Set<string>();
    for (const o of out) {
        const file = path.join(outDir, `${o.doc.id}.yaml`);
        fs.mkdirSync(path.dirname(file), {recursive: true});
        o.yaml = withRevision(file, o.doc, [...hdr, `Source: ${o.rec.where}`]);
        fs.writeFileSync(file, o.yaml);
        written.add(path.relative(outDir, file));
    }
    if (!only) {
        // remove definitions zhc no longer has
        const walk = (d: string): string[] => fs.readdirSync(d, {withFileTypes: true})
            .flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
        for (const f of walk(outDir)) if (f.endsWith('.yaml') && !written.has(path.relative(outDir, f))) fs.unlinkSync(f);
        writeCoverage(covDir, zhc.version, out.map((o) => o.rec), out.map((o) => o.yaml));
    }
    process.stderr.write(`herdsman-gen: ${out.length} definitions from zhc ${zhc.version} in ${((Date.now() - t0) / 1000).toFixed(1)} s\n`);
}

if (require.main === module) {
    main().then(() => process.exit(0), (e) => {
        console.error(e);
        process.exit(1);
    });
}
